export const welcomeGuide = (role: UserRole): WelcomeGuide => GUIDES[role];

const storageKey = (login: string) => `inspector.welcome.v1.${login}`;

/** Хранилище может быть недоступно (приватное окно, запрет сайта): тогда подсказка просто показывается каждый раз. */
export const isWelcomeSeen = (login: string): boolean => {
  try {
    return window.localStorage.getItem(storageKey(login)) === '1';
  } catch {
    return false;
  }
};

export const markWelcomeSeen = (login: string): void => {
  try {
    window.localStorage.setItem(storageKey(login), '1');
  } catch {
    /* без хранилища подсказка появится снова: это не ошибка */
  }
};
