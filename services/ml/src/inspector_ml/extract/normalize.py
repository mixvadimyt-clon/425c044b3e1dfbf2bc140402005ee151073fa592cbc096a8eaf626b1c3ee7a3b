"""Нормализация значений параметров матрицы.

Одно и то же значение в ПД, РД и ИД пишут по-разному, и без приведения к общему виду
движок сравнения объявит несопоставимыми одинаковые величины:

- числа — `17 140,2` (с неразрывным пробелом), `3 009.4`, `1225,8` → `17140.2`, `3009.4`, `1225.8`;
- единицы площади — `кв. м`, `кв.м`, `м2`, `м²` → `м²`;
- классы бетона — кириллическая `В25`, `B 25`, `В12,5` → латинские `B25`, `B12.5`.

**Кириллица в марках — не мелочь.** На одной странице ПД (F0106, стр. 49) рядом стоят
`фундаментная плита B40` (латиница) и `пилоны, колонны, стены В60` (кириллица), а OCR на
русском тексте почти всегда выбирает кириллическую «В» (грабли 5). Без приведения к
латинице `B40` из РД и `В40` из ПД — разные строки, и проверка ложно «срабатывает».
"""

from __future__ import annotations

import re
import unicodedata

# Буквы, неразличимые на глаз: в марках и шифрах они приходят то кириллицей, то латиницей.
LOOKALIKE = str.maketrans("АВСЕНКМОРТХУЁ", "ABCEHKMOPTXYЕ")
# Все виды дефисов и минусов — к обычному дефису. Мягкий перенос (U+00AD) в тексте PDF стоит
# на месте настоящего дефиса («1­го этажа», «Тамбур­шлюз»), и без приведения ни этаж
# из заголовка, ни номер помещения не разбираются.
DASHES = str.maketrans("­‐‑‒–—―−", "--------")

_SPACES = re.compile(r"[\s  -​ ⁠]+")
# 17 140,2 · 3 009.4 · 1225,8 — разряды отделяются пробелом, дробная часть запятой или точкой.
# Ветка с разделителем разрядов идёт первой и требует хотя бы одной группы: иначе «1030,7»
# разбиралось бы как «103» — первая ветка забирала три цифры и останавливалась.
_NUMBER = re.compile(r"[-+]?\d{1,3}(?:[\s  ]\d{3})+(?:[.,]\d+)?|[-+]?\d+(?:[.,]\d+)?")
# В25 · B 25 · В12,5 · B22.5 — цифра до 2 знаков, дробная часть только «.5».
# Запятая после марки разделяет характеристики («B40,F150,W6»), поэтому в хвосте запрещена
# только цифра: иначе класс в спецификации материалов не находится вовсе.
#
# Пробел между буквой и числом допускается только у ЗАГЛАВНОЙ «В»: строчная «в» перед числом —
# это русский предлог. «предельной высоты зданий согласно ГПЗУ в 50 м» давало класс B50, из-за
# чего ожидаемое значение M-055 в ПД становилось неоднозначным (B30, B35, B50) и проверка уходила
# в CLARIFICATION_REQUIRED вместо сравнения. Замер по корпусу (19 разобранных документов,
# 759 совпадений марки в тексте): правка убирает ровно эту точку и не трогает ни одну верную —
# настоящие марки пишутся «(В30)», «кл. В35», «B35P4F(I)», «Бетон В35 по ГОСТ». Слитную строчную
# («в30») оставляем: так марку пишут в рукописных актах ИД. Поймано 22.09 на «Речников ул. 7-7».
_CONCRETE = re.compile(r"(?<![0-9A-Za-zА-Яа-яЁё])(?:[BВ]\s?|[bв])(\d{1,2}(?:[.,]5)?)(?!\d)")

AREA_UNITS = re.compile(r"(?:кв\.?\s*м|м\s*[²2])(?![а-яa-z])", re.IGNORECASE)
AREA_UNIT = "м²"

#: Классы бетона по ГОСТ 26633 — ими ограничен `enum_values` матрицы для M-055.
CONCRETE_CLASSES = (
    "B3.5", "B5", "B7.5", "B10", "B12.5", "B15", "B20", "B22.5",
    "B25", "B27.5", "B30", "B35", "B40", "B45", "B50", "B55", "B60",
)  # fmt: skip


def collapse(text: str) -> str:
    """Схлопнуть любые пробелы в один и убрать края: PDF щедр на неразрывные и узкие пробелы."""
    return _SPACES.sub(" ", unicodedata.normalize("NFC", text).translate(DASHES)).strip()


def key(text: str) -> str:
    """Ключ для сравнения наименований: без регистра, без «ё», без лишних пробелов и точек."""
    return collapse(text).casefold().replace("ё", "е").strip(" .:;,-—–")


def number(text: str) -> float | None:
    """Первое число в тексте. Разделитель разрядов — пробел, дробной части — запятая или точка."""
    match = _NUMBER.search(collapse(text))
    if match is None:
        return None
    try:
        return float(_SPACES.sub("", match.group()).replace(",", "."))
    except ValueError:  # pragma: no cover — регулярка не пропускает такие строки
        return None


#: Дата в ячейке: «26.03.23», «18.05.2022». `number` разобрал бы её как 26.03.
_DATE = re.compile(r"\d{1,2}[.,/-]\d{1,2}[.,/-]\d{2,4}")
#: Ведущий ноль перед второй цифрой: «02.22», «007», «01,5». Так пишут месяц с годом, индекс
#: или номер по порядку, но не измеренную величину — площадь «02.22» никто не записывает.
_LEADING_ZERO = re.compile(r"^0\d")
#: Что не мешает считать ячейку значением: скобки, знаки препинания, звёздочка сноски, градус.
_TRIM = " 	.,;:()[]*°"


def only_number(text: str) -> float | None:
    """Число, если ячейка целиком им и является — с единицей измерения, но без прочих слов.

    `number` находит первое число в любой строке, и для ячейки таблицы этого мало:

    - «м2» разбирается как **2**;
    - «не более 30 000» — как **30000**;
    - «26.03.23» — как **26.03**;
    - «Экспликация помещений 1 этажа» — как **1**.

    В ТЭП такие ячейки стоят в одной строке с показателем, а значением берётся самая правая
    числовая — и площадь застройки превращалась в норматив ГПЗУ «не более 7000». По корпусу
    неоднозначной оказалась половина строк с якорем, поэтому правило строгое: если кроме числа
    и единицы измерения в ячейке есть что-то ещё, это не значение.

    Отдельно отсекается **ведущий ноль**: «02.22» на живом прогоне пилота дало «общую площадь
    здания 2.22 м²» при уверенности 0.998. Пришло оно с распознанного плана, где сотни обрывков
    размеров, и строка показателя подхватила первый попавшийся. Величину с ведущим нулём
    не пишут — так выглядят месяц с годом, индекс или номер по порядку.
    """
    cleaned = collapse(text)
    if not cleaned or _DATE.search(cleaned):
        return None
    match = _NUMBER.search(cleaned)
    if match is None:
        return None
    if _LEADING_ZERO.match(match.group()):
        return None
    rest = AREA_UNITS.sub(" ", f"{cleaned[: match.start()]} {cleaned[match.end() :]}")
    if rest.strip(_TRIM):
        return None
    try:
        return float(_SPACES.sub("", match.group()).replace(",", "."))
    except ValueError:  # pragma: no cover — регулярка не пропускает такие строки
        return None


def has_area_unit(text: str) -> bool:
    """Есть ли в тексте единица площади (`кв. м`, `м2`, `м²`)."""
    return AREA_UNITS.search(text) is not None


def concrete_class(text: str) -> str | None:
    """Класс бетона в каноническом виде `B25` / `B12.5`, если он есть в тексте.

    Буква приводится к латинице, дробная часть — к точке. Отвергаются значения вне ГОСТ
    (`B9`, `B100`): в спецификациях рядом стоят марки арматуры `А500С` и диаметры, и без
    проверки по списку регулярка ловит мусор.
    """
    for match in _CONCRETE.finditer(collapse(text)):
        value = f"B{match.group(1).replace(',', '.')}"
        if value in CONCRETE_CLASSES:
            return value
    return None


def lookalike(text: str) -> str:
    """Привести визуально одинаковые кириллические буквы к латинице (для марок и шифров)."""
    return collapse(text).upper().translate(LOOKALIKE)
