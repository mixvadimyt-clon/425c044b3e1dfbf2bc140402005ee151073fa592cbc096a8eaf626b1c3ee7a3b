"""Общий результат извлечения: что нашли на странице и где именно.

`Found` — это ещё не `Extraction`: в нём нет ни файла, ни стадии, ни роли фрагмента. Их
добавляет [api.py](api.py), когда знает, из какого документа пришла страница. Так извлекатели
параметров остаются чистыми функциями от страницы и их легко проверять на фикстурах.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Found:
    """Значение параметра, найденное на конкретной странице."""

    rule_key: str | None
    """Атомарная контрольная точка: «пом. 1.09», «Фундаментная плита». `None` — параметр целиком."""

    raw_value: str
    """Значение как в документе — оно попадёт в протокол и в выгрузку."""

    value: float | str | bool | None
    """Нормализованное значение: число в базовых единицах или марка в каноническом виде."""

    page: int
    bbox: list[float]
    snippet: str
    unit: str | None = None
    method: str = "table"
    """Как нашли: `table`, `regex`, `lexicon` — идёт в `Extraction.method` и помогает при разборе ошибок."""
