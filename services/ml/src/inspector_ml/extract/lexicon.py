"""Словарь наименований конструкций для `rule_key` M-055.

**Чего здесь нет.** Синонимов наименования показателя («Площадь жилого здания» ↔ «Общая площадь
здания») — они лежат в матрице, в `semantic_anchors`, и приходят в `CompareRequest.matrix`.
Матрица правится без
релиза ML, и копия тех же синонимов в коде разошлась бы с ней молча.

**Что здесь есть и почему.** Наименование конструкции — это не имя параметра, а имя **атомарной
точки** (`rule_key`): поля для него в матрице нет, а список нужен, потому что элемент почти
всегда стоит в косвенном падеже («бетонирование **фундаментной плиты**»). Поэтому здесь:

1. канонические наименования конструкций и их написания в документах;
2. лёгкое сопоставление по основам слов — без морфологического анализатора и без внешних моделей
   (ограничение проекта: только локальные зависимости);
3. правило «подземной части» — уточнение ключа по отрицательной отметке уровня (`_qualify`).
"""

from __future__ import annotations

import re
from functools import lru_cache

from inspector_ml.extract.normalize import key

#: Канонические наименования конструкций для `rule_key` M-055 и их написания в документах.
#:
#: Ключ — то, что уйдёт в протокол и в выгрузку; значения — как это пишут проектировщики.
#: Сопоставление идёт по основам, поэтому падежи перечислять не нужно: «фундаментная плита»
#: находит и «фундаментной плиты», и «ж/б фундаментную плиту».
#:
#: Аббревиатур («БСС», «СВГ») здесь намеренно нет: они входят в шифры и номера актов
#: («АОСР №1А-БСС», «17_ПД/25-СВГ»), и по ним конструкция определялась бы неверно — в акте
#: на стену в грунте номер содержит «БСС».
CONSTRUCTION_ELEMENTS: dict[str, tuple[str, ...]] = {
    "Стена в грунте": ("стена в грунте", "стены в грунте"),
    "Фундаментная плита": ("фундаментная плита", "плита фундаментная", "фундаментной плиты"),
    "Буросекущиеся сваи": ("буросекущиеся сваи", "буросекущаяся свая"),
    "Вертикальные конструкции": (
        "пилоны колонны стены",
        "вертикальные конструкции",
        "колонны и стены",
        "стены и пилоны",
    ),
    "Бетонная подготовка": ("бетонная подготовка",),
    "Плиты перекрытия": ("плита перекрытия", "плиты перекрытий", "перекрытия"),
    "Обвязочная балка": ("обвязочная балка", "распределительный пояс"),
    "Ростверк": ("ростверк",),
    "Лестницы": ("лестничные марши", "лестницы"),
    "Стены подвала": ("стены подвала", "наружные стены подвала"),
}

#: Конструкции, у которых класс бетона зависит от того, подземная это часть или надземная.
UNDERGROUND_SPLIT = frozenset({"Вертикальные конструкции"})
#: Отрицательная отметка уровня: «-3 по +1», «на отм. -13.750», «отм.-13,750».
BELOW_ZERO = re.compile(r"(?:^|[\s(.«])-\s?\d")

#: Слова, которые в названии конструкции ничего не уточняют и мешают сопоставлению.
NOISE = frozenset({"монолитный", "монолитная", "монолитных", "ж/б", "жб", "железобетонный", "железобетонная"})

_WORD = re.compile(r"[а-яa-z0-9]+", re.IGNORECASE)
#: Сколько букв отбрасываем с конца слова вместо морфологии: «плита» и «плиту» дают основу «плит».
_ENDING = 2
#: Минимальная длина слова, которое вообще имеет смысл резать.
_MIN_WORD = 4

#: Падежные окончания существительных и прилагательных — всё, чем формы одного слова
#: отличаются после общего начала. Нулевое окончание («ростверк», «лестниц», «стен») — пустая строка.
INFLECTIONS = frozenset(
    {
        "", "а", "я", "о", "е", "ы", "и", "у", "ю", "ь", "й",
        "ой", "ей", "ий", "ый", "ая", "яя", "ое", "ее", "ые", "ие", "ую", "юю",
        "ов", "ев", "ам", "ям", "ах", "ях", "ом", "ем", "ым", "им", "ых", "их",
        "ами", "ями", "ого", "его", "ому", "ему", "ыми", "ими",
    }
)  # fmt: skip
#: Общее начало двух форм не короче этого — иначе совпадения случайны («сте», «пли»).
MIN_COMMON = 4


def same_word(left: str, right: str) -> bool:
    """Формы одного слова: общее начало не короче `MIN_COMMON`, а остатки — падежные окончания.

    Отрезать у каждого слова ровно две буквы, как делает `stems`, мало: у форм с нулевым
    окончанием основы расходятся. «ростверк» → `ростве`, а «ростверка» → `роствер`; «лестниц» →
    `лестн`, а «лестницы» → `лестни` — и класс бетона из акта ИД «бетонная смесь для ростверка»
    терял конструкцию.

    Просто общее начало не годится: у «стена» и «стенд», «плита» и «плитка» оно тоже четыре буквы.
    Разница в остатке — «д» и «ка» падежными окончаниями не бывают, а «а», «ов», «ей» бывают.

    Разрез ищется не только по концу общего начала, а по любой точке внутри него: у «лестничных»
    и «лестничные» общее начало `лестничны`, и остатки по нему — «х» и «е», ни одно не окончание.
    Правильный разрез на букву раньше: `лестничн` + «ых» / «ые».
    """
    if left == right:
        return True
    common = 0
    for a, b in zip(left, right, strict=False):
        if a != b:
            break
        common += 1
    return any(
        left[cut:] in INFLECTIONS and right[cut:] in INFLECTIONS for cut in range(common, MIN_COMMON - 1, -1)
    )


@lru_cache(maxsize=65536)
def words(phrase: str) -> tuple[str, ...]:
    """Значимые слова фразы в сравнимом виде: без регистра, «ё» и слов-шумов.

    С кешем: якоря матрицы и тексты ячеек сравниваются в цикле по 132 параметрам, и одна и та же
    фраза разбирается на слова тысячи раз.
    """
    return tuple(w for w in _WORD.findall(key(phrase)) if w not in NOISE)


def stems(phrase: str) -> tuple[str, ...]:
    """Основы значимых слов фразы: «ж/б фундаментную плиту» → `('фундамент', 'плит')`."""
    return tuple(w[:-_ENDING] if len(w) >= _MIN_WORD else w for w in words(phrase))


def contains(text: str, phrase: str) -> bool:
    """Встречаются ли слова фразы в тексте подряд (допускается одно лишнее слово между ними).

    Слова сравниваются как формы одного слова (`same_word`), а не буквально: элемент почти всегда
    стоит в косвенном падеже — «бетонирование фундаментной плиты», «для ростверка», «устройство
    лестниц».

    Запас в одно слово нужен для перечислений вроде «пилоны, колонны, стены -3 по +1»: между
    словами там стоят запятые и отметки, но порядок слов сохраняется.
    """
    needle, haystack = words(phrase), words(text)
    if not needle or len(needle) > len(haystack):
        return False
    for start in range(len(haystack) - len(needle) + 1):
        position = start
        for word in needle:
            while position < len(haystack) and not same_word(haystack[position], word):
                if position - start >= len(needle):  # слишком далеко разошлись — это другая фраза
                    break
                position += 1
            if position >= len(haystack) or not same_word(haystack[position], word):
                break
            position += 1
        else:
            return True
    return False


def element(text: str) -> str | None:
    """Каноническое наименование конструкции, упомянутой в тексте, если оно узнаётся."""
    for canonical, variants in CONSTRUCTION_ELEMENTS.items():
        if any(contains(text, variant) for variant in variants):
            return _qualify(canonical, text)
    return None


def _qualify(canonical: str, text: str) -> str:
    """Уточнить наименование по отметке уровня: отрицательная отметка — подземная часть.

    «Вертикальные конструкции» проходят через всё здание, и класс бетона у них меняется по
    высоте: в ПД это отдельные строки «пилоны, колонны, стены -3 по +1 В60», «+6 до +16 В50».
    Без уточнения все они складываются в одну контрольную точку с разными значениями, и проверка
    уходит в «нужен выбор источника». Эксперт организаторов разделил их так же — в эталоне точка
    называется «Вертикальные конструкции подземной части».

    Это наше правило, а не правило матрицы: мы решили его оставить.
    Ключ точки — `object_id + parameter_code + location`, поэтому если в
    скрытой части организаторы назовут её иначе, крутить надо здесь.
    """
    if canonical not in UNDERGROUND_SPLIT or not BELOW_ZERO.search(text):
        return canonical
    return f"{canonical} подземной части"
