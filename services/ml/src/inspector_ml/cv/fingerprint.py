"""Отпечаток изображённого на листе.

Наименование листа из штампа сопоставляет ПД с РД плохо, и это не недоработка метрики:
в графу 4 на разных стадиях пишут разное. В ПД — **что изображено** («План 4, 8 этажей на
отм. +13.750 +27.950»), в РД — **раздел и номер листа** («Архитектурные решения надземной
части. Планы Р 16»). Сравнивать нечего.

Зато на самом чертеже есть то, что обязано совпадать у двух изображений одного и того же:
**отметки уровня**. Они проставляются по СПДС в метрах с тремя знаками после запятой и со
знаком — `+13.750`, `-5.400`. План четвёртого этажа несёт свою отметку и в проектной, и в
рабочей документации, потому что это одно и то же место в здании.

Проверка на Речникове: у листов АР в ПД совпали с РД наборы `{+40.375, +42.150}`,
`{+43.925, +45.700}`, `{+49.520, +49.610, +49.660, +49.800}` — причём соседние листы ПД легли
на соседние листы РД с постоянным сдвигом в 44 страницы. Это выровненная последовательность
этажей, а не случайные попадания.

**Редкость отметки решает всё.** `+0.000` стоит на сотне листов и не различает ничего, а
`+43.925` — на двух, и его совпадение почти доказывает пару. Поэтому вес отметки — логарифм
обратной частоты по самому комплекту (та же идея, что IDF в поиске): часто встреченная отметка
весит около нуля сама собой, без списков исключений.

Отметки берутся из уже разобранного JSON, поэтому растр здесь не нужен и `PARSER_VERSION`
не меняется. Сходство миниатюр появится отдельно вместе с кешем рендеров.
"""

from __future__ import annotations

import math
import re
from collections import Counter
from collections.abc import Iterable, Mapping

from inspector_ml.extract.normalize import collapse

#: Отметка уровня: знак, метры (до двух цифр) и ровно три знака дробной части — `+13.750`.
#:
#: Знак обязателен намеренно. Без него в отметки попадают размеры и номера, а с ним ложных
#: срабатываний почти нет: числа именно такого вида в чертеже больше ничем не бывают.
#: Минус в любом начертании приводится к дефису ещё в `collapse`.
ELEVATION = re.compile(r"[-+]\s?\d{1,2}[.,]\d{3}\b")

#: Сколько отметок должно быть на листе, чтобы он вообще участвовал в сопоставлении по ним.
#: Одна отметка — это чаще всего высота узла или подпись сечения, набор начинается с двух.
MIN_MARKS = 2

#: Минимальный суммарный вес общих отметок, ниже которого совпадение считаем случайным.
#:
#: Порог задан в весах, а не в количестве: две редкие отметки доказывают больше, чем пять
#: общеупотребительных. Отметка, встреченная на сотой доле листов, весит около 4.6 — то есть
#: одной по-настоящему редкой хватает, а на `+0.000` с весом 0.2 не наберётся и десятка.
MIN_SHARED_WEIGHT = 3.0


def elevations(text: str) -> frozenset[str]:
    """Отметки уровня, найденные в тексте листа, в каноническом виде `+13.750`."""
    return frozenset(match.group().replace(" ", "").replace(",", ".") for match in ELEVATION.finditer(collapse(text)))


def weights(documents: Iterable[frozenset[str]]) -> dict[str, float]:
    """Вес каждой отметки: логарифм обратной доли листов, на которых она встречается.

    Отметка, стоящая на всех листах, получает ноль и перестаёт влиять на оценку.
    """
    marks = list(documents)
    total = len(marks)
    if not total:
        return {}
    seen = Counter(mark for document in marks for mark in document)
    return {mark: math.log(total / count) for mark, count in seen.items()}


def shared_weight(left: frozenset[str], right: frozenset[str], weight: Mapping[str, float]) -> float:
    """Суммарный вес отметок, общих для двух листов."""
    return sum(weight.get(mark, 0.0) for mark in left & right)


def similarity(left: frozenset[str], right: frozenset[str], weight: Mapping[str, float]) -> float:
    """Насколько похожи наборы отметок: взвешенный коэффициент Жаккара, 0 — ничего общего.

    Обычный Жаккар здесь обманывает: два листа с единственной отметкой `+0.000` дают
    формальную единицу. Поэтому и пересечение, и объединение считаются в весах, а совпадения
    слабее `MIN_SHARED_WEIGHT` отбрасываются целиком.
    """
    if len(left) < MIN_MARKS or len(right) < MIN_MARKS:
        return 0.0
    common = shared_weight(left, right, weight)
    if common < MIN_SHARED_WEIGHT:
        return 0.0
    whole = sum(weight.get(mark, 0.0) for mark in left | right)
    return common / whole if whole else 0.0
