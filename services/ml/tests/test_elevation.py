"""M-009 «Абсолютная отметка 0.000».

Строки — из документов обучающей части: Новослободская (в том числе эталон организаторов PZ-009,
ПД КР2 стр. 53), Алтуфьевское 79Б, «Пример нарушений на чертежах». Шаблон матрицы из них видит
только обороты с «соответствует абсолютной отметке».
"""

from __future__ import annotations

import pytest

from inspector_ml import matrix
from inspector_ml.contracts.events import MatrixParam
from inspector_ml.extract import elevation
from inspector_ml.extract.api import extractor_for


@pytest.fixture
def m009() -> MatrixParam:
    param = matrix.param("M-009")
    if param is None:  # pragma: no cover — матрица лежит в репозитории рядом
        pytest.skip(f"нет {matrix.params_path()}")
    return param


def page(*texts: str, number: int = 1) -> dict:
    blocks = [
        {"id": f"b{i}", "type": "text", "text": t, "bbox": [0, 0.1 * i, 1, 0.1 * i + 0.05]} for i, t in enumerate(texts)
    ]
    return {"page": number, "blocks": blocks}


def marks(m009: MatrixParam, *texts: str) -> list[float | str | bool | None]:
    return [f.value for f in elevation.extract(m009, [page(*texts)])]


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # Новослободская, ПЗ и почти все тома — этого оборота шаблон матрицы не видит
        ("За относительную отметку 0,000 принята абсолютная отметка 159,95 м., что соответствует отметке чис", 159.95),
        ("15. За относительную отметку 0,000 принята абс. отм. 159,95 м.", 159.95),
        ("За относительную отметку нуля принята абсолютная отметка 159,95. Верхняя относительная", 159.95),
        (
            "3. За относительную отметку ±0.000 принята отметка чистого пола первого этажа, соответствующая"
            " абсолютной отметке 159.95.",
            159.95,
        ),
        ('Абсолютная отметка 159.95 "0.000" здания', 159.95),
        ("± 0,000 м (абс. отметка) 159,95", 159.95),
        # Алтуфьевское 79Б
        ("1. Условная отметка 0,000 соответствует абсолютной отметке 164,18. 2. Проект котлована разработан с", 164.18),
        (
            "2. За отм. 0.000 принята отм. чистого пола 1 этажа здания, что соответствует абсолютной отм. 164,18."
            " 3. Проектируемое здание относится к",
            164.18,
        ),
        ("Относительная отм.0.000 уровня чистого пола 1-го этажа соответствует абсолютной отм.163.00.", 163.0),
        # «Пример нарушений на чертежах»
        ("Относительной отметке здания ±0.000 соответствует абсолютная отметка 138.000.", 138.0),
        ("высотной посадки здания, абсолютная отметка 0,000 принята 138,00; - удобного и безоп", 138.0),
        ("Высотная отметка соответствует абсолютной отметке: 0,000 = 138,00.", 138.0),
        # латинская «o» в «отметкoй» — так в текстовом слое тома 4.1.1
        (
            "Относительной отметке нуля 0.000 соответствует уровень чистого пола первого этажа с абсолютной"
            " отметкoй 138.00 в Балтийской системе координат.",
            138.0,
        ),
    ],
)
def test_how_the_zero_mark_is_written(m009: MatrixParam, text: str, expected: float) -> None:
    assert marks(m009, text) == [pytest.approx(expected)]


def test_gold_page_takes_only_the_zero(m009: MatrixParam) -> None:
    """Эталон PZ-009, ПД КР2 стр. 53: на странице две абсолютные отметки, ноль — только первая."""
    text = (
        "Отметка нуля принята на абсолютной отметке +159.950. Отметка верха фундаментной плиты равна"
        " -13,750. В качестве решения фундамента предусмотрена фундаментная плита на естественном"
        " основании.что соответствует абс.отметке 146.200."
    )

    assert marks(m009, text) == [pytest.approx(159.95)]


@pytest.mark.parametrize(
    "text",
    [
        # абсолютная отметка дна котлована, нуля во фразе нет
        "- разработка грунта котлована до отм. -9.950 (абс. отм. 150.000);",
        # ноль назван, но в другой фразе
        "За отметку 0,000 принята отметка чистого пола; уровень грунтовых вод на абс. отм. 152,30",
        # между нулём и абсолютной отметкой — другая относительная отметка, абсолютная — её
        "За отметку 0,000 принят пол 1 этажа, низ плиты на отм. -14,950 (абс. отм. 145,00)",
        # относительная отметка вместо абсолютной
        "За относительную отметку 0,000 принята абсолютная отметка -1,200",
    ],
)
def test_other_absolute_marks(m009: MatrixParam, text: str) -> None:
    assert marks(m009, text) == []


class TestOneDocument:
    def test_same_mark_on_many_pages(self, m009: MatrixParam) -> None:
        text = "За относительную отметку 0,000 принята абсолютная отметка 159,95 м."
        found = elevation.extract(m009, [page(text, number=4), page(text.replace("159,95", "159.950"), number=9)])

        assert [(f.rule_key, f.value, f.unit, f.page) for f in found] == [("Отметка 0.000", 159.95, "м", 4)]

    def test_different_marks_are_all_kept(self, m009: MatrixParam) -> None:
        """Том сноса: у каждого сносимого здания свой ноль — выбирать за инспектора нельзя."""
        found = marks(
            m009,
            "Относительная отм.0.000 уровня чистого пола 1-го этажа соответствует абсолютной отм.163.00.",
            "Относительная отм.0.000 уровня чистого пола 1- го этажа соответствует абсолютной отм.165.00.",
        )

        assert found == [pytest.approx(163.0), pytest.approx(165.0)]

    def test_dispatch(self) -> None:
        assert extractor_for("M-009") is elevation.extract
