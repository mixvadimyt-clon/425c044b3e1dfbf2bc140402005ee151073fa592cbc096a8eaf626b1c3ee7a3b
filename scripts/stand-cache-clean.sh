#!/usr/bin/env bash
# Еженедельная очистка кеша растров страниц на стенде.
#
# Растры (`renders/{sha256}/{dpi}/{page}.png`) копятся всю экспертизу, пока эксперты листают
# чертежи: около 500 КБ на лист, то есть тысяча просмотренных листов — полгигабайта. Диск стенда
# 50 ГБ делят исходные файлы, кеш разбора и ночные копии базы, поэтому место возвращаем таймером.
#
# Предела объёма у кеша нет намеренно: настоящий LRU с учётом времени доступа дороже задачи,
# которую решает. Удалять растры безопасно — при следующем
# запросе лист отрисуется заново примерно за 0.15 с, в отличие от разбора, который без кеша
# считался бы с OCR по минуте на страницу.
#
# Чистим только `renders/`: команда ml не трогает соседний `parsed/`, восстановление которого
# стоило бы часов. Каталог кеша целиком не удаляем именно поэтому.
#
# Ставится таймером systemd из infra/stand/setup.sh (воскресенье 04:30, после ночной копии базы).
# Вручную:  ./scripts/stand-cache-clean.sh
set -euo pipefail
cd "$(dirname "$0")/.."

COMPOSE=(docker compose -f docker-compose.app.yml)
if [ -f .env.stand ]; then COMPOSE+=(--env-file .env.stand); fi

log() { printf '%s %s\n' "$(date -Is)" "$*"; }

if [ -z "$("${COMPOSE[@]}" ps -q ml 2>/dev/null)" ]; then
  log "контейнер ml не запущен — растры не копятся, чистить нечего"
  exit 0
fi

log "очистка кеша растров"
"${COMPOSE[@]}" exec -T ml inspector-ml cache renders --clear
